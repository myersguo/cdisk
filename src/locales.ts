export type Locale = "en" | "zh" | "zh-Hant" | "ja" | "ko" | "es" | "fr";

export const LOCALE_OPTIONS: { value: Locale; native: string; english: string }[] = [
  { value: "en", native: "English", english: "English" },
  { value: "zh", native: "简体中文", english: "Simplified Chinese" },
  { value: "zh-Hant", native: "繁體中文", english: "Traditional Chinese" },
  { value: "ja", native: "日本語", english: "Japanese" },
  { value: "ko", native: "한국어", english: "Korean" },
  { value: "es", native: "Español", english: "Spanish" },
  { value: "fr", native: "Français", english: "French" },
];

const messages: Record<Locale, Messages> = { en, zh, "zh-Hant": zhHant, ja, ko, es, fr };
const supported = new Set<Locale>(LOCALE_OPTIONS.map(option => option.value));

export function resolveLocale(stored: string | null | undefined, systemLanguage: string): Locale {
  if (stored && supported.has(stored as Locale)) return stored as Locale;
  const system = systemLanguage.replaceAll("_", "-").toLowerCase();
  if (/^zh-(hant|tw|hk|mo)/.test(system)) return "zh-Hant";
  if (system.startsWith("zh")) return "zh";
  if (system.startsWith("ja")) return "ja";
  if (system.startsWith("ko")) return "ko";
  if (system.startsWith("es")) return "es";
  if (system.startsWith("fr")) return "fr";
  return "en";
}

function detectLocale(): Locale {
  try {
    return resolveLocale(
      globalThis.localStorage?.getItem("cdisk.locale"),
      globalThis.navigator?.languages?.[0] || globalThis.navigator?.language || "en",
    );
  } catch {
    return "en";
  }
}

let currentLocale = detectLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setCurrentLocale(locale: Locale) {
  currentLocale = locale;
  try {
    document.documentElement.lang = locale === "zh-Hant" ? "zh-Hant" : locale;
  } catch {
    // Non-browser tests do not expose document.
  }
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let value: string = messages[currentLocale][key] ?? en[key];
  for (const [name, replacement] of Object.entries(params ?? {})) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function localeTag(locale = currentLocale): string {
  return locale === "zh" ? "zh-CN" : locale === "zh-Hant" ? "zh-TW" : locale;
}

